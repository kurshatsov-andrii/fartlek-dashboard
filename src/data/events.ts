const allBlueprints: EventBlueprint[] = [
  ...upcomingBlueprints,
  ...finishedBlueprints,
];

const upcomingYear = 2026;
const finishedYear = 2025;

const WEATHER_CONDITIONS = ["Сонячно", "Хмарно", "Невеликий дощ", "Мінлива хмарність"];

const buildEvent = (b: EventBlueprint, i: number): SportEvent => {
  const city = getCityByName(b.city) ?? UKRAINE_CITIES[0];
  const org = ORGANIZERS.find((o) => o.id === b.organizerId) ?? ORGANIZERS[0];
  const year = b.state === "upcoming" ? upcomingYear : finishedYear;
  const date = isoDate(year, b.month, b.day);
  const id = `evt-${i + 1}`;
  const status: EventStatus = b.status ?? (b.state === "finished" ? "finished" : "registration_open");
  return {
    id,
    title: b.title,
    slug: slugify(b.title) + "-" + id,
    description: b.description,
    shortDescription:
      b.description.length > 110
        ? b.description.slice(0, 107) + "..."
        : b.description,
    image: IMAGES[i % IMAGES.length],
    date,
    city: city.name,
    region: city.region,
    coordinates: { lat: city.lat, lng: city.lng },
    category: b.category,
    status,
    state: b.state,
    registrationLink: `https://fartlek.events/register/${id}`,
    organizerId: org.id,
    organizerName: org.name,
    participants: b.participants,
    maxParticipants: b.maxParticipants,
    views: b.views,
    tags: b.tags,
    distance: b.distance,
    price: b.price,
    featured: b.featured,
    weather:
      b.state === "upcoming"
        ? {
            temp: 12 + ((i * 3) % 18),
            condition: WEATHER_CONDITIONS[i % WEATHER_CONDITIONS.length],
          }
        : undefined,
  };
};

export const EVENTS: SportEvent[] = allBlueprints.map(buildEvent);

export const UPCOMING_EVENTS: SportEvent[] = EVENTS.filter(
  (e) => e.state === "upcoming",
);

export const FINISHED_EVENTS: SportEvent[] = EVENTS.filter(
  (e) => e.state === "finished",
);

export const FEATURED_EVENTS: SportEvent[] = EVENTS.filter((e) => e.featured);

export const getEventById = (id: string): SportEvent | undefined =>
  EVENTS.find((e) => e.id === id);
